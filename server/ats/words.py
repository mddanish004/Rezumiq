def heading_id(line: str):
    key = re.sub(r"[^a-z& ]+", " ", line.lower()).strip()
    key = re.sub(r"\s+", " ", key)
    if not key or len(line) > 40 or len(key.split()) > 5:
        return None
    for hid, pat in SECTION_HEADINGS:
        if re.match(pat, key):
            return hid
    return None
